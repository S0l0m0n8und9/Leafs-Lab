"""Rebuild the verified watch companion from downloaded, reconciled CSVs."""
import argparse
import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from analysis.current_game_proof import analyze

parser = argparse.ArgumentParser()
parser.add_argument('--raw-dir', type=Path, required=True)
parser.add_argument('--bundle', type=Path, required=True)
args = parser.parse_args()
bundle = json.loads(args.bundle.read_text())
sources = []
inputs = {}
game_ids = {g['id'] for g in bundle['seasons'][0]['games']}
for source in bundle['sources']:
    kind = source['kind']
    files = list(args.raw_dir.glob(kind + '-*.csv'))
    assert len(files) == 1, f'Expected one original {kind} CSV'
    original = files[0].read_bytes()
    assert 'sha256:' + hashlib.sha256(original).hexdigest() == source['hash']
    rows = list(csv.DictReader(original.decode('utf-8-sig').splitlines()))
    base = {'gameId', 'gameDate', 'opposingTeam', 'situation', 'team', 'playerTeam', 'playerId', 'name'}
    fields = {
        'teams': {'goalsFor', 'goalsAgainst', 'xGoalsFor', 'xGoalsAgainst', 'shotsOnGoalFor', 'shotsOnGoalAgainst', 'unblockedShotAttemptsFor', 'unblockedShotAttemptsAgainst', 'highDangerShotsFor', 'highDangerShotsAgainst'},
        'skaters': {'I_F_goals', 'I_F_xGoals', 'I_F_shotsOnGoal', 'I_F_unblockedShotAttempts', 'OnIce_F_xGoals', 'OnIce_A_xGoals', 'icetime'},
        'goalies': {'xGoals', 'goals', 'icetime'},
    }[kind] | base
    inputs[kind] = [{k: v for k, v in r.items() if k in fields} for r in rows if r['gameId'] in game_ids]
    sources.append({**source, 'sha256': source['hash'].removeprefix('sha256:'),
                    'bytes': len(original), 'rows': len(rows), 'headers': list(rows[0])})
data = {'season': '20262027', 'source_manifest': {'season': '20262027',
        'purpose': 'Verified published current-season watch companion', 'sources': sources}, 'inputs': inputs}
result = analyze(data)
pin = {'season': result['season'], 'max_game_date': result['coverage']['last_date'],
       'game_ids': [g['game_id'] for g in result['games']],
       'source_hashes': {s['kind']: s['hash'] for s in sources},
       'team': result['five_on_five'], 'games': result['games'],
       'marchenko': next(p for p in result['players'] if p['player_id'] == '8480893'),
       'marchenko_games': [{'game_id': g['game_id'], 'date': g['date'], 'opponent': g['opponent'],
           'ixg': float(r['I_F_xGoals']), 'shots': float(r['I_F_shotsOnGoal']),
           'goals': float(r['I_F_goals']), 'onice_xgf': float(r['OnIce_F_xGoals']),
           'onice_xga': float(r['OnIce_A_xGoals'])}
           for g in result['games'] for r in inputs['skaters']
           if r['gameId'] == g['game_id'] and r['playerId'] == '8480893' and r['situation'] == '5on5'],
       'bobrovsky': [g for g in result['goalies'] if g['name'] == 'Sergei Bobrovsky' and g['strength'] in {'all', '5on5', '4on5'}]}
companion = ROOT / 'src/watchSnapshot.ts'
guard = companion.read_text().split('export function matchesWatchSnapshot', 1)[1]
companion.write_text("// Generated by scripts/refresh_watch.py from reconciled provider CSVs.\nimport type { Bundle, Season } from './data.js';\nexport const watchSnapshot = " + json.dumps(pin, indent=2) + " as const;\n\nexport function matchesWatchSnapshot" + guard)
for path, value in [('analysis/data/current-2026.json', data),
                    ('analysis/current-proof-results.json', result),
                    ('public/data/leafs-lab.json', bundle)]:
    (ROOT / path).write_text(json.dumps(value, indent=2) + '\n')
print(json.dumps({k: result[k] for k in ['coverage', 'five_on_five', 'source_reconciliation_notes', 'goalies']}, indent=2))
print(json.dumps(pin['marchenko'], indent=2))
